#!/usr/bin/env python3
"""Generates the alarm queue: SLOTS fixed slots on the player country.

  mod/common/scripted_effects/dsm_generated_queue.txt            slot copy / sort / insert / delete
  mod/common/scripted_triggers/dsm_generated_queue_triggers.txt  duplicate check
  mod/common/scripted_guis/dsm_generated_queue_sguis.txt         per-row delete buttons
  mod/common/customizable_localization/dsm_queue_custom_loc.txt  row and popup text
  mod/localization/<lang>/dsm_queue_l_<lang>.yml
  tools/gui_queue_rows.gui                                       list rows (included by gui_panel.gui)

Slot N lives in dsm_s<N>_<field>. Used slots are always 1..count, sorted by
date, so slot 1 is the next alarm. dsm_snew_* stages an alarm being added
and dsm_stmp_* is swap space. The scripted effects take the slot as a
parameter ($N$ is substituted textually, so dsm_s$N$_target -> dsm_s3_target).

dsm_f<K>_* hold the alarms that fired today, for the popup.

Re-run after editing:  python3 tools/gen_queue.py && python3 tools/build_gui.py
"""
from pathlib import Path

from gen_reasons import BOM, LANGS, REASONS, REPEATS, ROOT

TOOLS = Path(__file__).resolve().parent
MOD = TOOLS.parent / "mod"
HEADER = BOM + "# GENERATED by tools/gen_queue.py. Do not edit by hand."

SLOTS = 10
# target = days since 1836.1.1; anchor = day of month monthly/yearly repeats return to;
# num = stable number among alarms with the same reason; dup = 1 if that reason is used twice.
FIELDS = ["target", "year", "month", "day", "anchor", "reason", "repeat", "num", "dup"]
FIRED_FIELDS = ["reason", "num", "dup", "repeat", "next_year", "next_month", "next_day", "ended"]


def block(name, body, comment=None):
    out = [f"# {comment}"] if comment else []
    return out + [f"{name} = {{"] + ["\t" + l for l in body] + ["}", ""]


def chain(branches, fallback=None):
    out = []
    for i, (trig, eff) in enumerate(branches):
        kw = "if" if i == 0 else "else_if"
        out.append(f"{kw} = {{ limit = {{ {trig} }} {eff} }}")
    if fallback:
        out.append(f"else = {{ {fallback} }}")
    return out


def effects():
    out = [HEADER, ""]
    out += block("dsm_slot_copy", [
        "if = {",
        "\tlimit = { has_variable = dsm_s$FROM$_target }",
        *[f"\tset_variable = {{ name = dsm_s$TO$_{f} value = var:dsm_s$FROM$_{f} }}" for f in FIELDS],
        "}",
        "else = { dsm_slot_remove = { N = $TO$ } }",
    ], "Copies slot $FROM$ over slot $TO$ (an empty slot empties $TO$).")
    out += block("dsm_slot_remove", [f"remove_variable = dsm_s$N$_{f}" for f in FIELDS])
    out += block("dsm_slot_swap", [
        "dsm_slot_copy = { FROM = $A$ TO = tmp }",
        "dsm_slot_copy = { FROM = $B$ TO = $A$ }",
        "dsm_slot_copy = { FROM = tmp TO = $B$ }",
        "dsm_slot_remove = { N = tmp }",
    ])

    # Only one alarm is ever out of place (just inserted or just advanced), but a
    # full bubble sort is cheap at this size and can't get it wrong.
    passes = []
    for _ in range(SLOTS - 1):
        for n in range(1, SLOTS):
            passes.append(f"if = {{ limit = {{ has_variable = dsm_s{n + 1}_target "
                          f"var:dsm_s{n}_target > var:dsm_s{n + 1}_target }} "
                          f"dsm_slot_swap = {{ A = {n} B = {n + 1} }} }}")
    out += block("dsm_queue_sort", passes, "Sorts the used slots by date, soonest first.")

    out += block("dsm_queue_insert_new",
                 chain([(f"NOT = {{ has_variable = dsm_s{n}_target }}", f"dsm_slot_copy = {{ FROM = new TO = {n} }}")
                        for n in range(1, SLOTS + 1)]) + ["dsm_queue_sort = yes"],
                 "Puts the staged alarm (dsm_snew_*) in the first free slot, then re-sorts. No-op if full.")

    for n in range(1, SLOTS + 1):
        body = [f"dsm_slot_copy = {{ FROM = {m + 1} TO = {m} }}" for m in range(n, SLOTS)]
        body.append(f"dsm_slot_remove = {{ N = {SLOTS} }}")
        out += block(f"dsm_queue_delete_{n}", body,
                     f"Deletes slot {n} and moves the later ones up." if n == 1 else None)
    out += block("dsm_queue_clear", [f"dsm_slot_remove = {{ N = {n} }}" for n in range(1, SLOTS + 1)])

    refresh = ["set_variable = { name = dsm_queue_count value = 0 }"]
    for n in range(1, SLOTS + 1):
        refresh.append(f"if = {{ limit = {{ has_variable = dsm_s{n}_target }} "
                       f"change_variable = {{ name = dsm_queue_count add = 1 }} }}")
    for n in range(1, SLOTS + 1):
        same = " ".join(f"AND = {{ has_variable = dsm_s{m}_target var:dsm_s{m}_reason = var:dsm_s{n}_reason }}"
                        for m in range(1, SLOTS + 1) if m != n)
        refresh.append(f"if = {{ limit = {{ has_variable = dsm_s{n}_target }} "
                       f"set_variable = {{ name = dsm_s{n}_dup value = 0 }} "
                       f"if = {{ limit = {{ OR = {{ {same} }} }} set_variable = {{ name = dsm_s{n}_dup value = 1 }} }} }}")
    out += block("dsm_queue_refresh", refresh, "Recounts the queue and marks reasons used by more than one alarm.")

    taken = " ".join(f"AND = {{ has_variable = dsm_s{m}_target var:dsm_s{m}_reason = var:dsm_snew_reason "
                     f"var:dsm_s{m}_num = var:dsm_snew_num }}" for m in range(1, SLOTS + 1))
    out += block("dsm_new_assign_num", [
        "set_variable = { name = dsm_snew_num value = 1 }",
        "set_variable = { name = dsm_snew_dup value = 0 }",
        f"while = {{ limit = {{ OR = {{ {taken} }} }} change_variable = {{ name = dsm_snew_num add = 1 }} }}",
    ], "Gives the staged alarm the lowest number not used by another alarm with the same reason.")

    out += block("dsm_fired_reset", [f"remove_variable = dsm_f{k}_{f}" for k in range(1, SLOTS + 1)
                                     for f in FIRED_FIELDS] + ["remove_variable = dsm_f_last"])
    push = [(f"NOT = {{ has_variable = dsm_f{k}_reason }}",
             " ".join(f"set_variable = {{ name = dsm_f{k}_{f} value = var:dsm_snew_{f} }}"
                      for f in ["reason", "num", "dup", "repeat"])
             + f" set_variable = {{ name = dsm_f_last value = {k} }}")
            for k in range(1, SLOTS + 1)]
    out += block("dsm_fired_push", chain(push), "Records the staged alarm as fired today, for the popup.")
    nxt = [(f"var:dsm_f_last = {k}",
            " ".join(f"set_variable = {{ name = dsm_f{k}_next_{f} value = var:dsm_snew_{f} }}"
                     for f in ["year", "month", "day"]))
           for k in range(1, SLOTS + 1)]
    out += block("dsm_fired_set_next", chain(nxt), "Records the staged alarm's next date on the last fired entry.")
    ended = [(f"var:dsm_f_last = {k}", f"set_variable = {{ name = dsm_f{k}_ended value = 1 }}") for k in range(1, SLOTS + 1)]
    out += block("dsm_fired_set_ended", chain(ended), "Marks the last fired entry as a repeat that can't continue (year cap).")

    path = MOD / "common/scripted_effects/dsm_generated_queue.txt"
    path.write_text("\n".join(out), encoding="utf-8")

    trig = [HEADER, ""]
    queued = " ".join(f"AND = {{ has_variable = dsm_s{n}_target var:dsm_s{n}_target = var:dsm_target "
                      f"var:dsm_s{n}_reason = var:dsm_reason }}" for n in range(1, SLOTS + 1))
    trig += block("dsm_target_is_queued", ["has_variable = dsm_target", "has_variable = dsm_reason", f"OR = {{ {queued} }}"],
                  "True if an alarm with the picker's date and reason is already queued.")
    (MOD / "common/scripted_triggers/dsm_generated_queue_triggers.txt").write_text("\n".join(trig), encoding="utf-8")


def sguis():
    out = [HEADER, ""]
    for n in range(1, SLOTS + 1):
        out += block(f"dsm_delete_{n}_sgui", [
            "scope = country",
            f"is_shown = {{ has_variable = dsm_s{n}_target }}",
            f"effect = {{ dsm_queue_delete_{n} = yes dsm_queue_refresh = yes }}",
        ], "Row visibility and its delete button." if n == 1 else None)
    out += block("dsm_queue_empty_sgui", ["scope = country", "is_shown = { NOT = { has_variable = dsm_s1_target } }"])
    (MOD / "common/scripted_guis/dsm_generated_queue_sguis.txt").write_text("\n".join(out), encoding="utf-8")


def lookup(name, entries, fallback):
    """entries: (trigger, localization key)."""
    L = [f"{name} = {{", "\ttype = country"]
    for trig, key in entries + [("always = yes", fallback)]:
        L.append(f"\ttext = {{\n\t\ttrigger = {{ {trig} }}\n\t\tlocalization_key = {key}\n\t}}")
    return L + ["}", ""]


def custom_loc():
    out = [HEADER, ""]
    reasons = [rid for rid, _, _ in REASONS if rid]
    repeats = [rid for rid, *_ in REPEATS if rid]
    for n in range(1, SLOTS + 1):
        v = f"dsm_s{n}"
        used = f"has_variable = {v}_target"
        out += lookup(f"{v}_reason_text", [(f"{used} var:{v}_reason = {r}", f"DSM_ROW_REASON_{r}") for r in reasons], "DSM_EMPTY")
        out += lookup(f"{v}_num_text", [(f"{used} var:{v}_reason > 0 OR = {{ var:{v}_num > 1 var:{v}_dup = 1 }}",
                                         f"DSM_S{n}_NUM")], "DSM_EMPTY")
        out += lookup(f"{v}_repeat_text", [(f"{used} var:{v}_repeat = {r}", f"DSM_ROW_REPEAT_{r}") for r in repeats], "DSM_EMPTY")
    for k in range(1, SLOTS + 1):
        v = f"dsm_f{k}"
        out += lookup(f"{v}_line", [(f"has_variable = {v}_reason", f"DSM_F{k}_LINE")], "DSM_EMPTY")
        fired = f"has_variable = {v}_reason"
        out += lookup(f"{v}_reason_text", [(f"{fired} var:{v}_reason = {r}", f"DSM_FIRED_REASON_{r}") for r in reasons],
                      "DSM_FIRED_NO_REASON")
        out += lookup(f"{v}_num_text", [(f"{fired} var:{v}_reason > 0 OR = {{ var:{v}_num > 1 var:{v}_dup = 1 }}",
                                         f"DSM_F{k}_NUM")], "DSM_EMPTY")
        out += lookup(f"{v}_next_text", [(f"has_variable = {v}_next_year var:{v}_repeat = {r}", f"DSM_F{k}_NEXT_{r}")
                                          for r in repeats] + [(f"has_variable = {v}_ended", "DSM_FIRED_REPEAT_ENDED")],
                      "DSM_EMPTY")
    path = MOD / "common/customizable_localization/dsm_queue_custom_loc.txt"
    path.write_text("\n".join(out), encoding="utf-8")


def loc():
    def var(scope, name):
        return f"[{scope}.MakeScope.Var('{name}').GetValue|0]"

    body = []
    for rid, _, text in REASONS:
        if rid:
            body.append(f' DSM_ROW_REASON_{rid}:0 " – {text}"')
            body.append(f' DSM_FIRED_REASON_{rid}:0 "#v {text}#!"')
    body.append(' DSM_FIRED_NO_REASON:0 "#v Alarm#! (no reason given)"')
    body.append(' DSM_FIRED_REPEAT_ENDED:0 ". Its repeat has stopped: 1999 is the last year Date Stop supports"')
    for rid, _, phrase in REPEATS:
        if rid:
            body.append(f' DSM_ROW_REPEAT_{rid}:0 ", {phrase}"')
    for n in range(1, SLOTS + 1):
        date = ".".join(var("GetPlayer", f"dsm_s{n}_{f}") for f in ["year", "month", "day"])
        body.append(f' DSM_SLOT_ROW_{n}:0 "#v {date}#![GetPlayer.GetCustom(\'dsm_s{n}_reason_text\')]'
                    f'[GetPlayer.GetCustom(\'dsm_s{n}_num_text\')][GetPlayer.GetCustom(\'dsm_s{n}_repeat_text\')]"')
        body.append(f' DSM_S{n}_NUM:0 " ({var("GetPlayer", f"dsm_s{n}_num")})"')
    for k in range(1, SLOTS + 1):
        c = "ROOT.GetCountry"
        body.append(f' DSM_F{k}_LINE:0 "\\n• [{c}.GetCustom(\'dsm_f{k}_reason_text\')]'
                    f'[{c}.GetCustom(\'dsm_f{k}_num_text\')][{c}.GetCustom(\'dsm_f{k}_next_text\')]"')
        body.append(f' DSM_F{k}_NUM:0 " ({var(c, f"dsm_f{k}_num")})"')
        date = ".".join(var(c, f"dsm_f{k}_next_{f}") for f in ["year", "month", "day"])
        for rid, _, phrase in REPEATS:
            if rid:
                body.append(f' DSM_F{k}_NEXT_{rid}:0 ". Repeats {phrase}, next on #v {date}#!"')
    for lang in LANGS:
        path = MOD / f"localization/{lang}/dsm_queue_l_{lang}.yml"
        path.write_text(BOM + f"l_{lang}:\n" + "\n".join(body) + "\n", encoding="utf-8")


def gui():
    L = []
    for n in range(1, SLOTS + 1):
        L += [
            "flowcontainer = {",
            "\tdirection = horizontal",
            "\tspacing = 6",
            f"\tvisible = \"[GetScriptedGui('dsm_delete_{n}_sgui').IsShown( {ROOT} )]\"",
            f"\ttext_single = {{ text = \"DSM_SLOT_ROW_{n}\" parentanchor = vcenter "
            "minimumsize = { 350 0 } max_width = 350 elide = right }",
            "\tbutton_icon_cancel = {",
            "\t\tsize = { 24 24 }",
            "\t\tparentanchor = vcenter",
            "\t\ttooltip = \"DSM_DELETE_TOOLTIP\"",
            f"\t\tonclick = \"[GetScriptedGui('dsm_delete_{n}_sgui').Execute( {ROOT} )]\"",
            "\t}",
            "}",
        ]
    (TOOLS / "gui_queue_rows.gui").write_text("\n".join(L) + "\n")


def main():
    effects()
    sguis()
    custom_loc()
    loc()
    gui()
    print(f"generated a {SLOTS}-slot queue")


if __name__ == "__main__":
    main()
