def sgui_files():
    out = [BOM + "# GENERATED by tools/gen_reasons.py. Do not edit by hand.", ""]
    for rid, _, _ in REASONS:
        out.append(f"dsm_set_reason_{rid}_sgui = {{\n\tscope = country\n"
                   f"\teffect = {{ dsm_set_reason = {{ ID = {rid} }} }}\n}}")
    for rid, *_ in REPEATS:
        out.append(f"dsm_set_repeat_{rid}_sgui = {{\n\tscope = country\n"
                   f"\teffect = {{ dsm_set_repeat = {{ ID = {rid} }} }}\n}}")
        trig = (f"OR = {{ NOT = {{ has_variable = dsm_repeat }} var:dsm_repeat = 0 }}" if rid == 0
                else f"has_variable = dsm_repeat var:dsm_repeat = {rid}")
        out.append(f"dsm_repeat_is_{rid}_sgui = {{\n\tscope = country\n\tis_shown = {{ {trig} }}\n}}")
    out.append("dsm_has_reason_sgui = {\n\tscope = country\n"
               "\tis_shown = { has_variable = dsm_reason var:dsm_reason > 0 }\n}")
    (MOD / "common/scripted_guis/dsm_generated_sguis.txt").write_text("\n".join(out) + "\n", encoding="utf-8")


def custom_loc():
    def lookup(name, var, entries, fallback_key):
        lines = [f"{name} = {{", "\ttype = country", ""]
        for value, key in entries:
            lines.append(f"\ttext = {{\n\t\ttrigger = {{ has_variable = {var} var:{var} = {value} }}\n"
                         f"\t\tlocalization_key = {key}\n\t}}")
        lines.append(f"\ttext = {{\n\t\ttrigger = {{ always = yes }}\n\t\tlocalization_key = {fallback_key}\n\t}}")
        lines.append("}")
        return "\n".join(lines)

    reason_names = [(rid, f"DSM_REASON_{rid}") for rid, _, _ in REASONS if rid]
    reason_lines = [(rid, f"DSM_REASON_LINE_{rid}") for rid, _, _ in REASONS if rid]
    out = [BOM + "# GENERATED by tools/gen_reasons.py. Do not edit by hand.", ""]
    # Picker: the reason currently selected in the panel.
    out.append(lookup("dsm_reason_text", "dsm_reason", reason_names, "DSM_REASON_0"))
    # Status line / popup: the reason saved when Set was pressed (empty if none).
    out.append(lookup("dsm_armed_reason_line", "dsm_armed_reason", reason_lines, "DSM_EMPTY"))
    out.append(lookup("dsm_fired_reason_line", "dsm_fired_reason", reason_lines, "DSM_EMPTY"))
    out.append(lookup("dsm_armed_repeat_text", "dsm_armed_repeat",
                      [(rid, f"DSM_REPEAT_SUFFIX_{rid}") for rid, *_ in REPEATS if rid], "DSM_EMPTY"))
    out.append(lookup("dsm_fired_next_line", "dsm_fired_repeat",
                      [(rid, f"DSM_NEXT_LINE_{rid}") for rid, *_ in REPEATS if rid], "DSM_EMPTY"))
    path = MOD / "common/customizable_localization/dsm_custom_loc.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n\n".join(out) + "\n", encoding="utf-8")


def loc():
    next_date = ("#v [ROOT.GetCountry.MakeScope.Var('dsm_armed_year').GetValue|0]."
                 "[ROOT.GetCountry.MakeScope.Var('dsm_armed_month').GetValue|0]."
                 "[ROOT.GetCountry.MakeScope.Var('dsm_armed_day').GetValue|0]#!")
    body = [' DSM_EMPTY:0 ""']
    for cid, name in CATEGORIES:
        body.append(f' DSM_CATEGORY_{cid.upper()}:0 "{name}"')
    for rid, _, text in REASONS:
        body.append(f' DSM_REASON_{rid}:0 "{text}"')
        if rid:
            body.append(f' DSM_REASON_LINE_{rid}:0 "Reason: #v {text}#!"')
    for rid, button, suffix, phrase in REPEATS:
        body.append(f' DSM_REPEAT_{rid}:0 "{button}"')
        if rid:
            body.append(f' DSM_REPEAT_SUFFIX_{rid}:0 "{suffix}"')
            body.append(f' DSM_NEXT_LINE_{rid}:0 "Repeats {phrase}. Next stop: {next_date}"')
    for lang in LANGS:
        path = MOD / f"localization/{lang}/dsm_generated_l_{lang}.yml"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(BOM + f"l_{lang}:\n" + "\n".join(body) + "\n", encoding="utf-8")


def gui():
    """Reason picker window: category tabs, then that category's reasons."""
    def exe(sgui):
        return f"[GetScriptedGui('{sgui}').Execute( {ROOT} )]"

    def cat_visible(cid):
        has = f"GetVariableSystem.HasValue('dsm_reason_cat', '{cid}')"
        return f"Or( {has}, Not( GetVariableSystem.Exists('dsm_reason_cat') ) )" if cid == "general" else has

    # Lives in pause_border, the HUD's full-screen widget. It can't live in
    # timemanip: the HUD gives that container a fixed width, and clicks outside
    # it fall through. (A top-level widget in a new .gui file wasn't created.)
    L = [
        "### DATE STOP (mod): reason picker, left of the Date Stop panel. GENERATED by tools/gen_reasons.py",
        "widget = {",
        '\tname = "dsm_reason_window"',
        "\tvisible = \"[And( Not( IsPauseMenuShown ), "
        "And( GetVariableSystem.Exists('dsm_panel_open'), GetVariableSystem.Exists('dsm_reason_open') ) )]\"",
        "\tparentanchor = top|right",
        "\tposition = { -400 160 }",
        "\tsize = { 390 330 }",
        "\tusing = clickthrough_blocker",
        "\talwaystransparent = no",
        "\tbackground = { using = default_background }",
        "",
        "\tflowcontainer = {",
        "\t\tdirection = vertical",
        "\t\tposition = { 15 10 }",
        "\t\tspacing = 6",
        '\t\ttext_single = { text = "DSM_REASON_PANEL_TITLE" using = fontsize_large }',
        '\t\ttext_single = { text = "DSM_REASON_CURRENT" }',
    ]
    for row in (CATEGORIES[:3], CATEGORIES[3:]):
        L += ["\t\tflowcontainer = {", "\t\t\tdirection = horizontal", "\t\t\tspacing = 4"]
        for cid, _ in row:
            selected = cat_visible(cid)
            L.append(f"\t\t\tbutton_standard = {{ size = {{ 118 24 }} text = \"DSM_CATEGORY_{cid.upper()}\" "
                     f"enabled = \"[Not( {selected} )]\" "
                     f"onclick = \"[GetVariableSystem.Set('dsm_reason_cat', '{cid}')]\" }}")
        L.append("\t\t}")
    for cid, _ in CATEGORIES:
        items = [r for r in REASONS if r[1] == cid]
        L += ["\t\tflowcontainer = {", "\t\t\tdirection = vertical", "\t\t\tspacing = 4",
              f"\t\t\tvisible = \"[{cat_visible(cid)}]\""]
        for i in range(0, len(items), 2):
            L += ["\t\t\tflowcontainer = {", "\t\t\t\tdirection = horizontal", "\t\t\t\tspacing = 4"]
            for rid, _, _ in items[i:i + 2]:
                L.append(f"\t\t\t\tbutton_standard = {{ size = {{ 178 24 }} text = \"DSM_REASON_{rid}\" "
                         f"onclick = \"{exe(f'dsm_set_reason_{rid}_sgui')}\" "
                         f"onclick = \"[GetVariableSystem.Clear('dsm_reason_open')]\" }}")
            L.append("\t\t\t}")
        L.append("\t\t}")
    L += [
        "\t\tbutton_standard = { size = { 118 26 } text = \"DSM_CLOSE\" "
        "onclick = \"[GetVariableSystem.Clear('dsm_reason_open')]\" }",
        "\t}",
        "}",
    ]
    (TOOLS / "gui_reasons.gui").write_text("\n".join(L) + "\n")


def repeat_row():
    """`#@REPEAT_ROW` in gui_panel.gui: Off / Weekly / Monthly / Yearly. Selected one is disabled."""
    L = ["flowcontainer = {", "\tdirection = horizontal", "\tspacing = 4",
         '\ttext_single = { text = "DSM_REPEAT_LABEL" minimumsize = { 60 0 } parentanchor = vcenter }']
    for rid, *_ in REPEATS:
        selected = f"GetScriptedGui('dsm_repeat_is_{rid}_sgui').IsShown( {ROOT} )"
        L.append(f"\tbutton_standard = {{ size = {{ 68 24 }} text = \"DSM_REPEAT_{rid}\" tooltip = \"DSM_REPEAT_TOOLTIP\" "
                 f"enabled = \"[Not( {selected} )]\" "
                 f"onclick = \"[GetScriptedGui('dsm_set_repeat_{rid}_sgui').Execute( {ROOT} )]\" }}")
    L.append("}")
    (TOOLS / "gui_repeat_row.gui").write_text("\n".join(L) + "\n")


def main():
    ids = [r[0] for r in REASONS]
    assert ids == list(range(len(ids))), "reason ids must be 0..N in order"
    assert {r[1] for r in REASONS} <= {c for c, _ in CATEGORIES}
    sgui_files()
    custom_loc()
    loc()
    gui()
    repeat_row()
    print(f"generated {len(REASONS) - 1} reasons in {len(CATEGORIES)} categories, {len(REPEATS) - 1} repeat options")


if __name__ == "__main__":
    main()
