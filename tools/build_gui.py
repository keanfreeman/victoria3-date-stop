#!/usr/bin/env python3
"""Builds gui/timemanip.gui = vanilla timemanip.gui with our tick_of_day_icon
swapped in (clock button) and our widgets appended to pause_border (panel,
reason picker, auto-pause). `type timemanip` is left untouched.

gui_repeat_row.gui and gui_reasons.gui are generated by gen_reasons.py; run it first.

After a game patch: copy the new game/gui/timemanip.gui over
tools/timemanip.vanilla.gui and re-run:  python3 tools/build_gui.py
"""
import textwrap
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
MOD = TOOLS.parent / "mod"

lines = (TOOLS / "timemanip.vanilla.gui").read_text(encoding="utf-8-sig").split("\n")


def stepper(indent, field, label, value):
    """`#@STEPPER <field> <label loc> <value loc>` -> label, minus, value, plus.
    Buttons follow the in-game convention: click 1, shift-click 5, ctrl-click 10,
    calling dsm_<field>_<up|down>_<step>_sgui."""
    def sgui(d, step):
        return f"\"[GetScriptedGui('dsm_{field}_{d}_{step}_sgui').Execute( GuiScope.SetRoot( GetPlayer.MakeScope ).End )]\""

    def button(kind, d):
        return [
            f"\t{kind} = {{",
            "\t\tsize = { 26 26 }",
            "\t\tparentanchor = vcenter",
            "\t\tclick_modifiers = {",
            f"\t\t\tondefault = {sgui(d, 1)}",
            f"\t\t\tonshift = {sgui(d, 5)}",
            f"\t\t\tonctrl = {sgui(d, 10)}",
            "\t\t}",
            "\t}",
        ]

    body = (["flowcontainer = {",
             "\tdirection = horizontal",
             "\tspacing = 6",
             f"\ttext_single = {{ text = \"{label}\" minimumsize = {{ 60 0 }} parentanchor = vcenter }}"]
            + button("button_icon_minus_action", "down")
            + [f"\ttext_single = {{ text = \"{value}\" minimumsize = {{ 56 0 }} align = center|nobaseline parentanchor = vcenter }}"]
            + button("button_icon_plus_action", "up")
            + ["}"])
    return [indent + l for l in body]


def snippet(name):
    out = []
    for line in (TOOLS / name).read_text().rstrip("\n").split("\n"):
        indent = line[:len(line) - len(line.lstrip())]
        if line.strip().startswith("#@STEPPER"):
            out += stepper(indent, *line.split()[1:])
        elif line.strip().startswith("#@INCLUDE"):
            out += [indent + l if l else l for l in snippet(line.split()[1])]
        else:
            out.append(line)
    return out


def find_type(header):
    """Line of `type <name> = ... {`, which must appear exactly once."""
    hits = [n for n, l in enumerate(lines) if header in l]
    if len(hits) != 1:
        raise SystemExit(f"expected one '{header}' in timemanip.vanilla.gui, found {len(hits)} (game patch?)")
    return hits[0]


def end_of_block(first):
    """Index of the line closing the block opened on line `first`."""
    depth = 0
    for n in range(first, len(lines)):
        depth += lines[n].count("{") - lines[n].count("}")
        if depth == 0:
            return n
    raise ValueError("unclosed block")


# Clock button: swap in our version of the small tick_of_day_icon type (see
# the comment in gui_tick_of_day_icon.gui for why it lives there).
t = find_type("type tick_of_day_icon = widget {")
lines[t:end_of_block(t) + 1] = snippet("gui_tick_of_day_icon.gui")

# Panel, reason picker and auto-pause: one full-screen widget at the end of
# pause_border, the HUD's first and full-screen widget. Only this file defines
# pause_border, so this works alongside mods that replace timemanip.
# pause_border draws below the rest of the HUD (nested `layer`s are ignored),
# so these are placed in open map space left of the time controls and below
# the top bar. Full-screen also means clicks aren't clipped.
wrapper = [
    "### DATE STOP (mod): panel, reason picker and auto-pause. Built by tools/build_gui.py",
    "widget = {",
    '\tname = "dsm_root"',
    "\tsize = { 100% 100% }",
    "\talwaystransparent = yes",
    "\tvisible = \"[And( Not( IsPauseMenuShown ), Not( IsGameOverScreenShown ) )]\"",
    "",
]
for name in ["gui_panel.gui", "gui_reasons.gui"]:
    body = textwrap.dedent("\n".join(snippet(name))).split("\n")
    wrapper += ["\t" + l if l else l for l in body] + [""]
wrapper.append("}")

pb = find_type("type pause_border = widget {")
close = end_of_block(pb)
lines[close:close] = [""] + ["\t\t" + l if l else l for l in wrapper]

out = MOD / "gui/timemanip.gui"
text = "\n".join(lines)
assert text.count("{") == text.count("}"), "unbalanced braces"
out.write_text(text, encoding="utf-8")
print(f"wrote {out}")
