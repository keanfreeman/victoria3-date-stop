#!/usr/bin/env python3
"""Generates common/scripted_effects/dsm_generated_effects.txt.

Victoria 3 script has no way to read the current date as a number, only the
`game_date >= YYYY.MM.DD` trigger with a literal date. So we work out today's
date with a chain of those comparisons: one per year (1836..MAX_YEAR) and then
one per day of that year. Scripted-effect parameter substitution ($Y$) means
the per-day chain is written once, not once per year.

The Paradox calendar has no leap years, so every year is 365 days.

Re-run after editing:  python3 tools/gen_date_effects.py
"""
from pathlib import Path

MIN_YEAR = 1836
MAX_YEAR = 1999
MONTH_LENGTHS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
CUMULATIVE = [sum(MONTH_LENGTHS[:i]) for i in range(12)]

OUT = Path(__file__).resolve().parent.parent / "mod/common/scripted_effects/dsm_generated_effects.txt"


def chain(branches, fallback):
    """branches: list of (trigger_text, effect_text). Builds an if/else_if/else chain."""
    lines = []
    for i, (trig, eff) in enumerate(branches):
        kw = "if" if i == 0 else "else_if"
        lines.append(f"\t{kw} = {{ limit = {{ {trig} }} {eff} }}")
    lines.append(f"\telse = {{ {fallback} }}")
    return "\n".join(lines)


def main():
    out = ["﻿# GENERATED by tools/gen_date_effects.py. Do not edit by hand.", ""]

    # --- dsm_compute_today --------------------------------------------------
    out.append("# Sets dsm_today_year / dsm_today_month / dsm_today_day / dsm_today_doy")
    out.append(f"# and dsm_today (days since {MIN_YEAR}.1.1) on the current scope.")
    out.append("dsm_compute_today = {")
    branches = [
        (f"game_date >= {y}.1.1",
         f"set_variable = {{ name = dsm_today_year value = {y} }} dsm_compute_doy = {{ Y = {y} }}")
        for y in range(MAX_YEAR, MIN_YEAR, -1)
    ]
    out.append(chain(branches,
                     f"set_variable = {{ name = dsm_today_year value = {MIN_YEAR} }} dsm_compute_doy = {{ Y = {MIN_YEAR} }}"))
    out.append("\tset_variable = { name = dsm_today value = var:dsm_today_year }")
    out.append(f"\tchange_variable = {{ name = dsm_today subtract = {MIN_YEAR} }}")
    out.append("\tchange_variable = { name = dsm_today multiply = 365 }")
    out.append("\tchange_variable = { name = dsm_today add = var:dsm_today_doy }")
    out.append("}")
    out.append("")

    # --- dsm_compute_doy (parameter Y = year) -------------------------------
    out.append("# Internal: day-of-year chain for year $Y$.")
    out.append("dsm_compute_doy = {")
    branches = []
    for m in range(12, 0, -1):
        for d in range(MONTH_LENGTHS[m - 1], 0, -1):
            if m == 1 and d == 1:
                continue
            doy = CUMULATIVE[m - 1] + d - 1
            branches.append((f"game_date >= $Y$.{m}.{d}",
                             f"dsm_set_today_md = {{ M = {m} D = {d} DOY = {doy} }}"))
    out.append(chain(branches, "dsm_set_today_md = { M = 1 D = 1 DOY = 0 }"))
    out.append("}")
    out.append("")

    out.append("dsm_set_today_md = {")
    out.append("\tset_variable = { name = dsm_today_month value = $M$ }")
    out.append("\tset_variable = { name = dsm_today_day value = $D$ }")
    out.append("\tset_variable = { name = dsm_today_doy value = $DOY$ }")
    out.append("}")
    out.append("")

    # --- month tables for the target ----------------------------------------
    out.append("# Sets dsm_t_mlen (length of month dsm_t_month) and dsm_t_mcum")
    out.append("# (days in the year before that month).")
    out.append("dsm_compute_target_month_info = {")
    branches = [
        (f"var:dsm_t_month = {m}",
         f"set_variable = {{ name = dsm_t_mlen value = {MONTH_LENGTHS[m-1]} }} "
         f"set_variable = {{ name = dsm_t_mcum value = {CUMULATIVE[m-1]} }}")
        for m in range(12, 1, -1)
    ]
    out.append(chain(branches,
                     "set_variable = { name = dsm_t_mlen value = 31 } set_variable = { name = dsm_t_mcum value = 0 }"))
    out.append("}")
    out.append("")

    # --- day-of-year -> target month/day --------------------------------------
    out.append("# Converts dsm_t_doy (0..364) into dsm_t_month / dsm_t_day.")
    out.append("dsm_doy_to_target_md = {")
    branches = []
    for m in range(12, 1, -1):
        cum = CUMULATIVE[m - 1]
        branches.append((f"var:dsm_t_doy >= {cum}",
                         f"set_variable = {{ name = dsm_t_month value = {m} }} "
                         f"set_variable = {{ name = dsm_t_day value = var:dsm_t_doy }} "
                         f"change_variable = {{ name = dsm_t_day add = {1 - cum} }}"))
    out.append(chain(branches,
                     "set_variable = { name = dsm_t_month value = 1 } "
                     "set_variable = { name = dsm_t_day value = var:dsm_t_doy } "
                     "change_variable = { name = dsm_t_day add = 1 }"))
    out.append("}")
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
